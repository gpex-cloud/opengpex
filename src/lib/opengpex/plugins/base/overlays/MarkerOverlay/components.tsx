"use client";

import React, { useRef } from "react";
import {
  useEditorState,
  useOverlayRotationSync,
} from "@opengpex/editor/core/context";
import { TransformGizmo } from "@opengpex/editor/widgets/TransformGizmo";
import { TransformHud } from "@opengpex/editor/widgets/affordances";
import { useMarkerOverlayState, useMarkerToolLifecycle } from "./hooks";
import {
  useMarkerPreviewFastSync,
  useMarkerSelectionFastSync,
} from "./useFastSync";
import { useMarkerHudAnchor } from "./useMarkerHudAnchor";
import type { Layer } from "@opengpex/editor/core/types";
import { MARKER_REGISTRY } from "./marker/registry";

// ─── MarkerOverlayMain ───────────────────────────────────────────────────────────

/**
 * MarkerOverlayMain: SVG overlay for the marker tool.
 *
 * Renders in STAGE_OVERLAY (screen-space, above the canvas): a real-time SVG
 * drag preview during marker creation (MarkerDrawPreview), the selection
 * frames over marker layers (MarkerSelectionBox: active handles / detached
 * ghost / dimmed sibling ghosts) — both gated to the marker tool — and the
 * ALWAYS-MOUNTED marker delta chip (MarkerChipHud), which serves every
 * marker gesture regardless of the active tool.
 *
 * The preview SVG content is generated by core `markerToSvg` (see hooks.ts),
 * keeping the on-canvas preview pixel-identical to the rasterized output.
 *
 * Cursor feedback + Escape handling live in `useMarkerToolLifecycle`, which is
 * called unconditionally (before the early return) so its effects can gate on
 * `isMarkerMode` and clean up on tool switch — never violating hook ordering.
 */
export const MarkerOverlayMain = React.memo(function MarkerOverlayMain() {
  const { isMarkerMode } = useMarkerOverlayState();

  // Cursor + Escape lifecycle (self-gated on isMarkerMode; must run every render).
  // Returns THE escape ladder — the HUD's Exit button runs the same steps.
  const runEscape = useMarkerToolLifecycle(isMarkerMode);

  return (
    <>
      {/* The delta chip is NOT tool-gated: a marker layer can be moved or
          rotated by the generic LayerMoveHandler in any mode (pan-mode bare
          drag, Cmd spring drag), and its chip must follow. Chip-only — the
          framework renders no gizmo container for it. */}
      <MarkerChipHud />
      {!isMarkerMode ? null : (
        <>
          <MarkerDrawPreview />
          <MarkerSelectionBox onExit={runEscape} />
        </>
      )}
    </>
  );
});

// ─── MarkerChipHud ─────────────────────────────────────────────────────────────

/**
 * MarkerChipHud: the marker tool's chips-only TransformHud — the ONE owner
 * of every layer-target marker gesture's delta chip, in every mode.
 *
 * Keying: the chip anchors to the ACTIVE layer while it is a marker. That
 * key survives every dispatch path because all three movers
 * (`marker-move`, `marker-rotate`, the generic `LayerMoveHandler`) set the
 * dragged layer active in onStart — so the active layer id always equals
 * the gesture record's `targetId`, in the marker tool and outside it.
 * Non-marker active layers yield a null anchor and the chip stays hidden.
 *
 * The gizmo HUD (MarkerSelectionBox) deliberately carries NO delta: in the
 * marker tool both HUDs are alive, and a delta there would paint a second
 * chip for the same gesture. Gizmo follows the tool; the chip follows the
 * layer.
 */
const MarkerChipHud = React.memo(function MarkerChipHud() {
  const { activeLayer } = useEditorState();
  const isMarkerLayer =
    !!activeLayer && activeLayer.type === "vector" && !!activeLayer.markerData;
  const { getAnchorFrame } = useMarkerHudAnchor(
    isMarkerLayer && activeLayer ? activeLayer.id : null,
  );

  if (!isMarkerLayer || !activeLayer) return null;
  return (
    <TransformHud
      active
      getAnchorFrame={getAnchorFrame}
      delta={{ targetId: activeLayer.id }}
    />
  );
});

// ─── MarkerDrawPreview ─────────────────────────────────────────────────────────

/**
 * MarkerDrawPreview: camera-following SVG surface for the drag preview.
 *
 * The container div carries the camera transform (translate + scale) so the
 * inner SVG can draw in canvas-local coordinates. The `<g>` inner content is
 * imperatively updated by useMarkerPreviewFastSync (dirty-checked, 60fps),
 * mirroring BrushOverlay's StrokePreview pattern.
 */
const MarkerDrawPreview = React.memo(function MarkerDrawPreview() {
  const containerRef = useRef<HTMLDivElement>(null);
  const groupRef = useRef<SVGGElement>(null);
  const { activeFrame } = useEditorState();

  useMarkerPreviewFastSync(containerRef, groupRef);

  if (!activeFrame) return null;
  const { w, h } = activeFrame.canvas;

  return (
    <div
      ref={containerRef}
      className="absolute top-0 left-0 pointer-events-none"
      style={{
        transformOrigin: "0 0",
        willChange: "transform",
      }}
    >
      <svg
        width={w}
        height={h}
        viewBox={`0 0 ${w} ${h}`}
        className="block overflow-visible"
        style={{ width: `${w}px`, height: `${h}px` }}
      >
        <g ref={groupRef} />
      </svg>
    </div>
  );
});

// ─── MarkerSelectionBox ────────────────────────────────────────────────────────

/**
 * Three visual states for marker layers while the marker tool is active:
 *
 *  - ACTIVE   — the selected marker's kind equals the armed tool kind: full
 *               TransformGizmo (resize/rotate handles). The panel edits it.
 *  - INACTIVE — a marker is selected but the user armed a different kind from
 *               the panel: full-opacity ghost brackets, NO handles (geometry is
 *               not editable, exactly like the text tool's editing state). The
 *               panel edits the armed kind's next-marker preset instead.
 *  - GHOST    — every other visible marker layer: dimmed ghost brackets, so the
 *               selection stays unmistakable among them. Pure affordance
 *               ("this is a grabbable vector"), pointer-events none.
 *
 * The phase comes from `resolveMarkerToolState` (toolState.ts) — the single
 * derivation shared with the panel, the Escape ladder and click-to-arm. A single
 * click on any marker re-arms its kind (marker-move), so INACTIVE only ever
 * follows an explicit kind change.
 */
const MarkerSelectionBox = React.memo(function MarkerSelectionBox({ onExit }: { onExit: () => void }) {
  const { state, activeFrame, activeLayer } = useEditorState();
  const { toolState } = useMarkerOverlayState();
  const containerRef = useRef<HTMLDivElement>(null);
  const boxRef = useRef<HTMLDivElement>(null);

  const { layerId, phase } = toolState;
  // Shape-owned control points read the committed layer data; during a drag the
  // live geometry lives on the fast track, so they would lag the pointer — hide
  // them while a gesture is in progress (the pointer itself is the control point).
  const isInteracting = !!state.interaction.isInteracting;

  // TransformHud anchor: the active marker's true screen-space box, derived
  // LIVE per tick by the framework's anchor sync.
  const { getAnchorFrame } = useMarkerHudAnchor(layerId);

  // Rotate the whole overlay container with the canvas (counter-animation
  // protocol), same as ClipOverlay/LayerOverlay. The inner box stays axis-aligned
  // in this rotated container, so its resize handles keep working and the box
  // follows canvas rotation WITH a smooth tween (not a hard jump).
  useOverlayRotationSync(containerRef, activeFrame);
  useMarkerSelectionFastSync(boxRef, layerId);

  if (!activeFrame) return null;

  // Dimmed ghosts over every OTHER visible marker layer.
  const ghostLayers = activeFrame.layers.order
    .map((id) => activeFrame.layers.byId[id])
    .filter(
      (l): l is Layer =>
        !!l && l.type === "vector" && !!l.markerData && l.visible && l.id !== layerId,
    );

  return (
    <div
      ref={containerRef}
      className="absolute inset-0 pointer-events-none overflow-visible"
      // Above the whole LayerOverlay stack (its active item sits at zIndex 10
      // inside its own container) — same level as the text tool's PreEditFrame
      // — so the handles are never painted under the hover outlines / index
      // labels.
      style={{ zIndex: 20 }}
    >
      {ghostLayers.map((ghost) => (
        <MarkerGhost key={ghost.id} layerId={ghost.id} />
      ))}

      {/* ACTIVE: the editable marker presents through the TransformHud
          framework — the gizmo and the shape control points (inside the
          same rotated container via gizmoExtras) are framework
          affordances now. NO delta here: the always-mounted MarkerChipHud
          owns every layer-target marker chip; a delta on this HUD would
          paint a second chip for the same gesture. Press routing stays
          here: the marker handlers claim the HUD's `data-marker-gizmo`
          scope. */}
      {layerId && phase === "active" && activeLayer?.markerData && (
        <TransformHud
          active
          getAnchorFrame={getAnchorFrame}
          gizmo={{
            // Edge-resize mode: full-length hit strips on all four sides
            // (drag anywhere on a border for single-axis resize) plus the
            // visible midpoint ticks. The corner brackets stay as-is.
            outline: true,
            rotation: activeLayer?.rotation ?? 0,
            flip: activeLayer?.flip,
          }}
          pressScope="marker-gizmo"
          gizmoExtras={
            !isInteracting &&
            MARKER_REGISTRY.get(activeLayer.markerData.kind)?.renderHandles?.(
              activeLayer.markerData,
              activeLayer.bounding,
            )
          }
          actions={
            <button
              type="button"
              onClick={onExit}
              title="Exit (Esc)"
              aria-label="Exit"
              className="flex items-center outline-none rounded px-1 text-[10px] font-bold leading-none text-rose-400 hover:bg-white/10 pointer-events-auto cursor-pointer"
              style={{ height: '16px' }}
            >
              Esc
            </button>
          }
        />
      )}

      {/* INACTIVE (kind switched away): detached ghost brackets, NO handles —
          geometry is not editable, exactly like the text tool's editing
          state. Raw visualOnly gizmo: decoration carries no anchor-provider
          obligation, so it stays on the fast-sync box. */}
      {layerId && phase !== "active" && (
        <div
          ref={boxRef}
          className="absolute top-0 left-0 pointer-events-none"
          style={{
            display: "none",
            transformOrigin: "0 0",
            willChange: "transform, width, height",
          }}
        >
          <TransformGizmo visualOnly />
        </div>
      )}
    </div>
  );
});

/**
 * MarkerGhost: dimmed visual-only brackets over a NON-selected marker layer.
 * No hit zones — it must never intercept a click meant for the layer body
 * (move) or the canvas (draw). Camera + pose following reuses
 * useMarkerSelectionFastSync with its own box ref, one subscription per ghost.
 */
function MarkerGhost({ layerId }: { layerId: string }) {
  const boxRef = useRef<HTMLDivElement>(null);
  useMarkerSelectionFastSync(boxRef, layerId);
  return (
    <div
      ref={boxRef}
      data-marker-ghost={layerId}
      className="absolute top-0 left-0 pointer-events-none"
      style={{
        display: "none",
        transformOrigin: "0 0",
        willChange: "transform, width, height",
      }}
    >
      <TransformGizmo visualOnly dimmed />
    </div>
  );
}
